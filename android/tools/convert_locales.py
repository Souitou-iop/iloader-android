#!/usr/bin/env python3
"""Convert the React frontend locales (src/locales/*.json) to Android strings.xml.

Only English (the default resources) and Simplified Chinese are generated.
Run it again whenever the JSON files change:

    python3 android/tools/convert_locales.py

Conventions:
  * Keys become resource names by joining the path with "_": `app.donate` ->
    `app_donate`. Characters outside [a-z0-9_] are replaced by "_"; a name
    collision aborts the run. The mapping is written to `locale_keys.json`.
  * `{{name}}` placeholders become `%1$s`, `%2$s`, ... numbered by the
    alphabetical order of the placeholder names, so every language agrees.
  * JSON arrays become `<string-array>` resources.
  * `<tag>` markers used for rich text (`<discord>`, `<translation>`, ...) are
    kept literally in the string; the app parses them at runtime.
  * `zh_cn_extra.json` supplies zh-CN text for keys the upstream file lacks;
    anything still missing is left out, so Android falls back to English.
"""

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any, Dict, Iterator, List, Tuple

ROOT = Path(__file__).resolve().parents[2]
LOCALES_DIR = ROOT / "src" / "locales"
RES_DIR = ROOT / "android" / "app" / "src" / "main" / "res"
KEY_MAP_PATH = Path(__file__).resolve().parent / "locale_keys.json"
# Flat "dotted.key" -> text, fills keys the upstream zh_cn.json does not translate yet.
EXTRA_PATHS = {"zh_cn": Path(__file__).resolve().parent / "zh_cn_extra.json"}

# source file stem -> values directory
TARGETS = {
    "en": "values",
    "zh_cn": "values-zh-rCN",
}

PLACEHOLDER = re.compile(r"\{\{\s*([A-Za-z0-9_]+)\s*\}\}")

Value = Any  # str | List[str]


def flatten(tree: Dict[str, Any], prefix: str = "") -> Iterator[Tuple[str, Value]]:
    for key, value in tree.items():
        path = f"{prefix}{key}"
        if isinstance(value, dict):
            yield from flatten(value, path + ".")
        else:
            yield path, value


def resource_name(key: str) -> str:
    name = re.sub(r"[^a-z0-9_]", "_", key.lower())
    if name[0].isdigit():
        name = "k_" + name
    return name


def placeholder_names(text: str) -> List[str]:
    return sorted(set(PLACEHOLDER.findall(text)))


def convert_text(text: str) -> str:
    """Turn one i18next string into the body of an Android string resource."""
    names = placeholder_names(text)
    index = {name: i + 1 for i, name in enumerate(names)}
    formatted = bool(names)

    parts: List[str] = []
    last = 0
    for match in PLACEHOLDER.finditer(text):
        parts.append(escape_literal(text[last:match.start()], formatted))
        parts.append(f"%{index[match.group(1)]}$s")
        last = match.end()
    parts.append(escape_literal(text[last:], formatted))
    return "".join(parts)


def escape_literal(text: str, formatted: bool) -> str:
    out = []
    for ch in text:
        if ch == "&":
            out.append("&amp;")
        elif ch == "<":
            out.append("&lt;")
        elif ch == ">":
            out.append("&gt;")
        elif ch == "'":
            out.append("\\'")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "@":
            out.append("\\@")
        elif ch == "%" and formatted:
            out.append("%%")
        else:
            out.append(ch)
    result = "".join(out)
    # A leading "?" would be read as a theme attribute reference.
    return result


def build_xml(entries: Dict[str, Value]) -> str:
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by android/tools/convert_locales.py. Do not edit. -->",
        '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="MissingTranslation">',
    ]
    for name, value in entries.items():
        if isinstance(value, list):
            lines.append(f'    <string-array name="{name}">')
            for item in value:
                lines.append(f"        <item>{convert_text(item)}</item>")
            lines.append("    </string-array>")
        else:
            lines.append(f'    <string name="{name}">{convert_text(value)}</string>')
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def load_entries(path: Path) -> Dict[str, Value]:
    with path.open(encoding="utf-8") as fh:
        tree = json.load(fh)
    return dict(flatten(tree))


def convert(locales_dir: Path = LOCALES_DIR) -> Tuple[Dict[str, str], Dict[str, str]]:
    """Return ({values dir: xml}, {json key: resource name})."""
    english = load_entries(locales_dir / "en.json")
    key_map: Dict[str, str] = {}
    seen: Dict[str, str] = {}
    for key in english:
        name = resource_name(key)
        if name in seen:
            raise SystemExit(f"resource name collision: {key} and {seen[name]} -> {name}")
        seen[name] = key
        key_map[key] = name

    outputs: Dict[str, str] = {}
    for stem, values_dir in TARGETS.items():
        entries = load_entries(locales_dir / f"{stem}.json")
        extra_path = EXTRA_PATHS.get(stem)
        if extra_path and locales_dir == LOCALES_DIR and extra_path.exists():
            extra = json.loads(extra_path.read_text(encoding="utf-8"))
            entries = {**extra, **entries}
        resolved: Dict[str, Value] = {}
        for key, value in entries.items():
            if key not in key_map:
                print(f"warning: {stem}.json has unknown key {key}", file=sys.stderr)
                continue
            if isinstance(value, list) != isinstance(english[key], list):
                print(f"warning: {stem}.json key {key} changes type, skipped", file=sys.stderr)
                continue
            if placeholder_names(json.dumps(value)) != placeholder_names(json.dumps(english[key])):
                print(f"warning: {stem}.json key {key} has different placeholders, skipped", file=sys.stderr)
                continue
            resolved[key_map[key]] = value
        # Keep English order so the output diffs cleanly.
        ordered = {key_map[k]: resolved[key_map[k]] for k in english if key_map[k] in resolved}
        outputs[values_dir] = build_xml(ordered)
    return outputs, key_map


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--locales", type=Path, default=LOCALES_DIR)
    parser.add_argument("--res", type=Path, default=RES_DIR)
    parser.add_argument("--key-map", type=Path, default=KEY_MAP_PATH)
    args = parser.parse_args()

    outputs, key_map = convert(args.locales)
    for values_dir, xml in outputs.items():
        target = args.res / values_dir / "strings.xml"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(xml, encoding="utf-8")
        print(f"wrote {target}")
    args.key_map.write_text(
        json.dumps(key_map, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print(f"wrote {args.key_map}")


if __name__ == "__main__":
    main()
